"""Empirical firmware oracle index loader and verdict resolver for OpenWebNet frames.

Loads results/mcp_index.json generated by own-firmware-oracle, which records exact
client session responses, bus telegram emissions, and SHA-256 provenance from
live QEMU firmware execution on BTicino MH200N and MyHomeServer1 gateways.
"""

from __future__ import annotations

import hashlib
import json
import logging
import re
from pathlib import Path
from typing import Any

from openwebnet_mcp._paths import resolve_oracle_index

logger = logging.getLogger("openwebnet_mcp.firmware_oracle")

CANONICAL_WHERE_CANDIDATES: tuple[str, ...] = ("21", "31", "74", "1", "2", "11", "12")


def normalize_frame(frame: str) -> str:
    """Normalize OpenWebNet frame string for dictionary lookup."""
    f = frame.strip()
    if f and not f.startswith("*"):
        f = "*" + f
    if f and not f.endswith("##"):
        f = f + "##"
    return f


def _is_point_to_point_where(where: str) -> bool:
    """Return True if `where` is a plain point-to-point numeric address (not `0`, group `#...`, or compound `#4#...`)."""
    return bool(where) and where != "0" and where.isdigit() and 1 <= len(where) <= 4


def _candidate_template_frames(norm: str) -> list[str]:
    """Generate canonical WHERE-template candidate frames for an OpenWebNet frame."""
    if not (norm.startswith("*") and norm.endswith("##")) or norm in ("*#*1##", "*#*0##"):
        return []
    inner = norm[1:-2]
    tokens = inner.split("*")
    candidates: list[str] = []
    if inner.startswith("#"):
        # Status request (*#WHO*WHERE##) or dimension request/write (*#WHO*WHERE*DIM...##)
        if len(tokens) >= 2 and _is_point_to_point_where(tokens[1]):
            orig_where = tokens[1]
            for cand in CANONICAL_WHERE_CANDIDATES:
                if cand != orig_where:
                    new_tokens = [tokens[0], cand, *tokens[2:]]
                    candidates.append("*" + "*".join(new_tokens) + "##")
    else:
        # Command/status frame (*WHO*WHAT*WHERE##)
        if len(tokens) == 3 and _is_point_to_point_where(tokens[2]):
            orig_where = tokens[2]
            for cand in CANONICAL_WHERE_CANDIDATES:
                if cand != orig_where:
                    candidates.append(f"*{tokens[0]}*{tokens[1]}*{cand}##")
    return candidates


_RE_INTERFACE_SUFFIX = re.compile(r"#4#(\d+)$")


def _extract_interface_suffix(norm: str) -> str | None:
    """Return the `<IF>` digits if `norm` carries a `#4#<IF>` WHERE routing suffix."""
    if not (norm.startswith("*") and norm.endswith("##")) or norm in ("*#*1##", "*#*0##"):
        return None
    inner = norm[1:-2]
    tokens = inner.split("*")
    where_tok = ""
    if inner.startswith("#"):
        if len(tokens) >= 2:
            where_tok = tokens[1]
    elif len(tokens) >= 3:
        where_tok = tokens[2]
    m = _RE_INTERFACE_SUFFIX.search(where_tok)
    return m.group(1) if m else None


def _decode_bus_hex_ascii(bus_frames: list[str]) -> list[str]:
    """Decode space-separated hex SCS bus captures (e.g. `24 30 34 ... 0d`) to ASCII strings."""
    decoded: list[str] = []
    for raw in bus_frames:
        try:
            b = bytes.fromhex(raw.strip())
            decoded.append(
                b.decode("ascii", errors="ignore")
                .replace("\r", "\\r")
                .replace("\n", "\\n")
            )
        except ValueError:
            continue
    return decoded


_RE_ROUTED_INTERFACE_BUS = re.compile(r"^\$0?06E[C4]", re.IGNORECASE)


def _is_unrouted_interface_bus(norm: str, bus_frames: list[str]) -> bool:
    """Return True when `norm` requests `#4#<IF>` routing but `bus_frames` emit only local-bus SCS telegrams."""
    iface = _extract_interface_suffix(norm)
    if iface is None or not bus_frames:
        return False
    ascii_frames = [s for s in _decode_bus_hex_ascii(bus_frames) if s.startswith("$")]
    if not ascii_frames:
        return False
    return not any(_RE_ROUTED_INTERFACE_BUS.match(s) for s in ascii_frames)


class FirmwareOracle:
    """In-memory loader and query engine for empirical firmware execution verdicts."""

    def __init__(self, index_path: Path | None = None) -> None:
        self.explicit_path = index_path
        self.path: Path | None = None
        self.source_tier: str = "none"
        self.loaded: bool = False
        self.load_error: str | None = None
        self.generator: str | None = None
        self.format_version: str | None = None
        self.schema_version: str | None = None
        self.total_unique_inputs: int = 0
        self.verdicts_sha256: str | None = None
        self.computed_sha256: str | None = None
        self.hash_verified: bool | None = None
        self.gateways: list[dict[str, Any]] = []
        self.verdicts: dict[str, list[dict[str, Any]]] = {}

    def load(self) -> bool:
        """Load or reload the oracle index from disk. Returns True on success."""
        if self.explicit_path:
            resolved = self.explicit_path
            tier = "explicit"
        else:
            resolved, tier = resolve_oracle_index()

        self.source_tier = tier

        if not resolved or not resolved.is_file():
            self.loaded = False
            self.load_error = f"Oracle index not found (resolved: {resolved})"
            logger.debug(self.load_error)
            return False

        self.path = resolved
        try:
            with open(resolved, "r", encoding="utf-8") as f:
                data = json.load(f)

            self.generator = data.get("generator")
            self.format_version = data.get("format_version")
            self.schema_version = data.get("schema_version")
            if self.format_version and not self.format_version.startswith("1."):
                logger.warning(
                    "Unexpected oracle index format_version '%s' at %s (expected 1.x)",
                    self.format_version,
                    resolved,
                )

            self.total_unique_inputs = int(data.get("total_unique_inputs", 0))
            self.gateways = data.get("gateways", [])
            self.verdicts = data.get("verdicts", {})
            self.verdicts_sha256 = data.get("verdicts_sha256")

            # Cryptographic canonical hash verification
            if self.verdicts_sha256 and self.verdicts:
                canonical_json = json.dumps(
                    self.verdicts, sort_keys=True, separators=(",", ":")
                )
                self.computed_sha256 = hashlib.sha256(
                    canonical_json.encode("utf-8")
                ).hexdigest()
                self.hash_verified = self.computed_sha256 == self.verdicts_sha256
                if not self.hash_verified:
                    logger.warning(
                        "Oracle index hash mismatch at %s (expected: %s, computed: %s)",
                        resolved,
                        self.verdicts_sha256,
                        self.computed_sha256,
                    )
            else:
                self.computed_sha256 = None
                self.hash_verified = None

            self.loaded = True
            self.load_error = None
            logger.info(
                "Loaded firmware oracle index from %s [tier: %s] (%d inputs, %d gateways, hash: %s)",
                resolved,
                self.source_tier,
                len(self.verdicts),
                len(self.gateways),
                "verified" if self.hash_verified else ("mismatch" if self.hash_verified is False else "none"),
            )
            return True
        except Exception as err:
            self.loaded = False
            self.load_error = f"Failed to parse oracle index {resolved}: {err}"
            logger.warning(self.load_error, exc_info=True)
            return False

    def reload(self) -> bool:
        """Force reload from disk."""
        return self.load()

    def lookup(self, frame: str) -> list[dict[str, Any]] | None:
        """Look up empirical verdicts for an OpenWebNet frame.

        Returns a list of verdict dicts across tested gateways, or None if not indexed.
        """
        if not self.loaded:
            self.load()

        if not self.loaded:
            return None

        # Try exact string
        if frame in self.verdicts:
            return self.verdicts[frame]

        # Try normalized
        norm = normalize_frame(frame)
        if norm in self.verdicts:
            return self.verdicts[norm]

        return None

    def lookup_with_fallback(
        self, frame: str
    ) -> tuple[list[dict[str, Any]] | None, str | None]:
        """Look up empirical verdicts for a frame, falling back to canonical WHERE templates.

        Returns `(verdicts, matched_template_frame)` where `matched_template_frame` is None
        when matched directly, or the canonical frame string (e.g. `*1*1*21##`) when matched
        via WHERE-address substitution.
        """
        direct = self.lookup(frame)
        if direct is not None:
            return direct, None
        if not self.loaded:
            return None, None
        norm = normalize_frame(frame)
        for cand in _candidate_template_frames(norm):
            if cand in self.verdicts:
                return self.verdicts[cand], cand
        return None, None

    def _emulated_fleet_summary(self) -> str:
        """Format dynamic summary of emulated gateways in the index."""
        emulated = [
            f"{g.get('product')} `{g.get('version')}`"
            for g in self.gateways
            if g.get("status", "emulated") == "emulated" or g.get("suites")
        ]
        if not emulated:
            return "MyHomeServer1 `028206` / MH200N `010108`"
        return f"{len(emulated)} emulated gateways: {', '.join(emulated)}"

    def preflight_check(
        self, frame: str, gateway: str | None = None
    ) -> dict[str, Any]:
        """Evaluate whether a drafted frame is accepted or rejected by emulated gateways."""
        verdicts, matched_template = self.lookup_with_fallback(frame)
        norm = normalize_frame(frame)
        if not verdicts:
            return {
                "checked": False,
                "frame": norm,
                "matched_frame": None,
                "accepted_by": [],
                "rejected_by": [],
                "crashed_by": [],
                "unrouted_by": [],
                "warnings": [],
            }

        accepted_by: list[str] = []
        rejected_by: list[str] = []
        crashed_by: list[str] = []
        unrouted_by: list[str] = []
        target_gw_norm = gateway.strip().lower() if gateway else None
        target_rejected = False
        target_accepted = False
        target_crashed = False
        target_unrouted = False
        check_frame = matched_template or norm

        for v in verdicts:
            gw_prod = str(v.get("product", "Unknown"))
            gw_ver = str(v.get("version", ""))
            label = f"{gw_prod} ({gw_ver})" if gw_ver else gw_prod
            reply = str(v.get("reply", "silent")).strip().lower()
            verdict = str(v.get("verdict", "silent")).strip().lower()
            bus = v.get("bus_frames") or []

            is_crash = verdict == "crash"
            is_unrouted = verdict == "out" and _is_unrouted_interface_bus(check_frame, bus)
            is_accepted = (reply == "ack" or verdict == "out") and not is_crash and not is_unrouted

            if is_crash:
                if label not in crashed_by:
                    crashed_by.append(label)
                if label not in rejected_by:
                    rejected_by.append(label)
            elif is_unrouted:
                if label not in unrouted_by:
                    unrouted_by.append(label)
            elif is_accepted:
                if label not in accepted_by:
                    accepted_by.append(label)
            else:
                if label not in rejected_by:
                    rejected_by.append(label)

            if target_gw_norm and target_gw_norm in gw_prod.lower():
                if is_crash:
                    target_crashed = True
                    target_rejected = True
                elif is_unrouted:
                    target_unrouted = True
                elif is_accepted:
                    target_accepted = True
                else:
                    target_rejected = True

        warnings: list[str] = []
        ref_note = (
            f" (via template `{matched_template}`)" if matched_template else ""
        )
        if crashed_by:
            warnings.append(
                f"CRITICAL: `{norm}`{ref_note} crashes the gateway translator daemon on {len(crashed_by)} firmware(s) "
                f"({', '.join(crashed_by)})."
            )
        if unrouted_by:
            iface = _extract_interface_suffix(check_frame) or "?"
            warnings.append(
                f"UNROUTED BUS OUTPUT: {len(unrouted_by)} firmware(s) ({', '.join(unrouted_by)}) emit local-bus SCS telegrams "
                f"without `#4#{iface}` interface routing (`$06EC`/`$06E4`) for `{norm}`{ref_note}, cross-addressing a local "
                f"device instead of interface `{iface}`."
            )
        if target_gw_norm and target_crashed:
            warnings.append(
                f"Target gateway `{gateway}` crashes its translator daemon on `{norm}`{ref_note} in firmware emulation."
            )
        elif target_gw_norm and target_unrouted and not target_accepted:
            warnings.append(
                f"Target gateway `{gateway}` does NOT route `{norm}`{ref_note} across `#4#` — it emits an unrouted local-bus SCS frame."
            )
        elif target_gw_norm and target_rejected and not target_accepted:
            warnings.append(
                f"Target gateway `{gateway}` empirically rejects `{norm}`{ref_note} with NACK/SILENT in firmware emulation."
            )
        elif rejected_by and not accepted_by and not unrouted_by:
            warnings.append(
                f"All {len(rejected_by)} tested gateway firmware(s) reject `{norm}`{ref_note} ({', '.join(rejected_by)})."
            )
        elif accepted_by and rejected_by:
            warnings.append(
                f"Split gateway support for `{norm}`{ref_note}: accepted by {len(accepted_by)} ({', '.join(accepted_by)}), "
                f"rejected by {len(rejected_by)} ({', '.join(rejected_by)})."
            )

        return {
            "checked": True,
            "frame": norm,
            "matched_frame": matched_template or norm,
            "accepted_by": accepted_by,
            "rejected_by": rejected_by,
            "crashed_by": crashed_by,
            "unrouted_by": unrouted_by,
            "warnings": warnings,
        }

    def compare_gateways(
        self, frame: str | None = None, suite: str | None = None
    ) -> str:
        """Compare behaviour across the gateway fleet by frame, suite divergences, or fleet summary."""
        if not self.loaded:
            self.load()
        if not self.loaded:
            err_msg = self.load_error or "Oracle index could not be loaded"
            return f"**Error**: Oracle index unavailable: {err_msg}"

        if frame:
            verdicts, matched_template = self.lookup_with_fallback(frame)
            norm = normalize_frame(frame)
            if not verdicts:
                return (
                    f"# Cross-Gateway Comparison: `{norm}`\n\n"
                    f"*Frame `{norm}` has not yet been replayed against firmware test suites "
                    f"({self._emulated_fleet_summary()}).*"
                )
            template_note = (
                f" *(Matched via equivalent address template `{matched_template}`)*"
                if matched_template
                else ""
            )
            lines = [
                f"# Cross-Gateway Comparison: `{norm}`{template_note}",
                "",
                "| Gateway | Firmware | Reply | Verdict | Bus Frames | Emitted OWN | Suite |",
                "|---|---|---|---|---|---|---|",
            ]
            groups: dict[str, list[str]] = {}
            for v in verdicts:
                gw = str(v.get("product", "Unknown"))
                ver = str(v.get("version", "Unknown"))
                reply = str(v.get("reply", "silent")).upper()
                verdict = str(v.get("verdict", "silent")).upper()
                bus = ", ".join(v.get("bus_frames") or []) or "-"
                own = ", ".join(v.get("emitted_own") or []) or "-"
                st = str(v.get("suite", "-"))
                lines.append(
                    f"| **{gw}** | `{ver}` | `{reply}` | `{verdict}` | `{bus}` | `{own}` | `{st}` |"
                )
                key = f"{reply} + {verdict}"
                groups.setdefault(key, []).append(f"{gw} (`{ver}`)")

            lines.extend(["", "## Outcome Equivalence Classes"])
            for outcome, members in groups.items():
                lines.append(f"- **{outcome}** ({len(members)}): {', '.join(members)}")
            return "\n".join(lines)

        if suite:
            suite_norm = suite.strip().lower()
            divergent_frames: list[tuple[str, dict[str, list[str]]]] = []
            total_in_suite = 0
            for inp, vlist in sorted(self.verdicts.items()):
                matching = [
                    v for v in vlist if str(v.get("suite", "")).lower() == suite_norm
                ]
                if not matching:
                    continue
                total_in_suite += 1
                outcomes: dict[str, list[str]] = {}
                for v in matching:
                    key = f"{str(v.get('reply', '')).upper()}+{str(v.get('verdict', '')).upper()}"
                    outcomes.setdefault(key, []).append(str(v.get("product", "?")))
                if len(outcomes) > 1:
                    divergent_frames.append((inp, outcomes))

            if total_in_suite == 0:
                return f"# Suite Comparison: `{suite}`\n\n*No indexed frames found for suite `{suite}`.*"

            lines = [
                f"# Cross-Gateway Divergences in Suite `{suite}`",
                "",
                f"- **Frames in suite**: `{total_in_suite}`",
                f"- **Unanimous frames**: `{total_in_suite - len(divergent_frames)}`",
                f"- **Divergent frames**: `{len(divergent_frames)}`",
                "",
            ]
            if not divergent_frames:
                lines.append("*All emulated gateways agreed on every frame in this suite.*")
            else:
                lines.extend([
                    "| Frame | Outcome Breakdown |",
                    "|---|---|",
                ])
                for inp, outcomes in divergent_frames:
                    summary_parts = [
                        f"**{k}** ({', '.join(gws)})" for k, gws in outcomes.items()
                    ]
                    lines.append(f"| `{inp}` | {'; '.join(summary_parts)} |")
            return "\n".join(lines)

        # Default: full fleet status summary
        emulated_count = sum(
            1
            for g in self.gateways
            if g.get("status", "emulated") == "emulated" or g.get("suites")
        )
        lines = [
            "# Empirical Firmware Oracle Fleet Summary",
            "",
            f"- **Total Catalogued Gateways**: `{len(self.gateways)}` (`{emulated_count}` emulated)",
            f"- **Total Indexed Frame Inputs**: `{len(self.verdicts)}`",
            "",
            "| Gateway | Firmware | Status | Suites Executed |",
            "|---|---|---|---|",
        ]
        for g in self.gateways:
            gw = g.get("product", "Unknown")
            ver = g.get("version", "Unknown")
            suites = g.get("suites") or []
            status_val = g.get("status") or ("emulated" if suites else "catalogued")
            lines.append(
                f"| **{gw}** | `{ver}` | `{status_val}` | `{len(suites)}` |"
            )
        return "\n".join(lines)

    def format_verdict_markdown(
        self,
        frame: str,
        verdicts: list[dict[str, Any]] | None,
        matched_template: str | None = None,
    ) -> str:
        """Format empirical verdicts into a GitHub-flavored Markdown section."""
        norm = normalize_frame(frame)

        if not self.loaded:
            err_msg = self.load_error or "Oracle index could not be loaded"
            return (
                "## 🛡️ Empirical Firmware Oracle Verification\n"
                f"*⚠️ Oracle index unavailable: {err_msg}.*"
            )

        if not verdicts:
            return (
                "## 🛡️ Empirical Firmware Oracle Verification\n"
                f"*Frame `{norm}` has not yet been replayed against firmware test suites "
                f"({self._emulated_fleet_summary()}).*"
            )

        normalized_note = ""
        if matched_template and matched_template != norm:
            normalized_note = (
                f" *(Matched via equivalent address template `{matched_template}`)*"
            )
        elif frame.strip() != norm:
            normalized_note = f" *(Matched normalized frame `{norm}`)*"

        lines = [
            f"## 🛡️ Empirical Firmware Oracle Verification: `{norm}`{normalized_note}",
            "",
            "| Gateway | Firmware | Reply | Verdict | Bus Frames Emitted | Emitted OWN | Suite | Target SHA |",
            "|---|---|---|---|---|---|---|---|",
        ]

        for v in verdicts:
            gw = v.get("product", "Unknown")
            ver = v.get("version", "Unknown")
            raw_reply = str(v.get("reply", "silent")).strip().lower()
            if raw_reply == "ack":
                reply = "`ACK (*#*1##)`"
            elif raw_reply == "nack":
                reply = "`NACK (*#*0##)`"
            elif raw_reply == "silent":
                reply = "`SILENT`"
            elif raw_reply == "-":
                reply = "*No client reply*"
            else:
                reply = f"`{raw_reply}`"

            raw_verdict = str(v.get("verdict", "unknown")).lower()
            bus = v.get("bus_frames") or []
            check_frame = matched_template or norm
            is_unrouted = raw_verdict == "out" and _is_unrouted_interface_bus(check_frame, bus)
            if raw_verdict == "crash":
                verdict_badge = "`CRASH (Daemon Exit)`"
            elif is_unrouted:
                verdict_badge = "`OUT (Unrouted Local Bus)`"
            elif raw_verdict == "out":
                verdict_badge = "`OUT (Bus)`"
            elif raw_verdict == "silent":
                verdict_badge = "`SILENT (Drop)`"
            else:
                verdict_badge = f"`{raw_verdict}`"

            bus_str = f"`{', '.join(bus)}`" if bus else "*(none)*"

            emitted = v.get("emitted_own") or []
            emitted_str = f"`{', '.join(emitted)}`" if emitted else "*(none)*"

            suite = v.get("suite", "unknown")
            target_sha = (v.get("target_sha256") or "")[:12]
            sha_str = f"`{target_sha}`" if target_sha else "*(n/a)*"

            lines.append(
                f"| **{gw}** | `{ver}` | {reply} | {verdict_badge} | {bus_str} | {emitted_str} | `{suite}` | {sha_str} |"
            )

        lines.extend([
            "",
            "### 🔬 Ground Truth Analysis",
        ])

        for v in verdicts:
            gw = v.get("product", "Unknown")
            ver = v.get("version", "Unknown")
            reply = str(v.get("reply", "silent")).strip().lower()
            verdict = str(v.get("verdict", "unknown")).strip().lower()
            bus = v.get("bus_frames") or []
            emitted = v.get("emitted_own") or []
            suite = v.get("suite", "unknown")
            src = v.get("source_tsv", "")

            details = [f"- **{gw} ({ver})**:"]
            if reply == "ack":
                details.append("Gateway acknowledged the command (`*#*1##`).")
            elif reply == "nack":
                details.append("Gateway refused/rejected the command (`*#*0##`).")
            elif reply == "-":
                details.append("Gateway recorded no client session reply.")
            elif reply == "silent":
                details.append("Gateway was silent on the client session.")
            else:
                details.append(f"Gateway returned: `{reply}`.")

            if verdict == "crash":
                details.append(
                    "CRITICAL: Gateway translator daemon crashed/exited while processing this frame; "
                    "no valid translation completed."
                )
            elif verdict == "out" and _is_unrouted_interface_bus(matched_template or norm, bus):
                iface = _extract_interface_suffix(matched_template or norm) or "?"
                decoded = ", ".join(_decode_bus_hex_ascii(bus))
                details.append(
                    f"Dispatched {len(bus)} SCS bus telegram(s): `{', '.join(bus)}` (`{decoded}`). "
                    f"WARNING: Input requested interface `#4#{iface}`, but emitted SCS telegram(s) are unrouted "
                    "local-bus frames (no `$06EC`/`$06E4` interface bridge header)."
                )
            elif verdict == "out":
                details.append(
                    f"Dispatched {len(bus)} SCS bus telegram(s): `{', '.join(bus)}` (physical bus transmission confirmed)."
                )
            elif verdict == "silent":
                details.append("Frame consumed or dropped internally; no SCS bus telegrams emitted.")
            elif bus:
                details.append(f"Dispatched {len(bus)} SCS bus telegram(s): `{', '.join(bus)}`.")
            else:
                details.append("No SCS bus telegrams emitted.")

            if emitted:
                details.append(f"Emitted session responses: `{', '.join(emitted)}`.")

            if src:
                details.append(f"Provenance: suite `{suite}` in `{src}`.")

            lines.append(" ".join(details))

        # Integrity & provenance footer
        hash_status_text = (
            "verified"
            if self.hash_verified is True
            else ("MISMATCH" if self.hash_verified is False else "unverified")
        )
        source_name = self.path.name if self.path else "index.json"
        lines.extend([
            "",
            f"*(Oracle provenance: {self.source_tier} index `{source_name}`, SHA-256: {hash_status_text})*",
        ])

        return "\n".join(lines)

    def status(self) -> dict[str, Any]:
        """Return diagnostic status information."""
        if not self.loaded:
            self.load()

